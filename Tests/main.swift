import Foundation

var checks = 0
func expect(_ value: @autoclosure () -> Bool, _ name: String) {
    checks += 1
    if !value() { fputs("FAIL: \(name)\n", stderr); exit(1) }
}

let converter = LayoutConverter.standard
expect(converter.convert("ghbdtn")?.text == "привет", "English to Russian")
expect(converter.convert("руддщ")?.text == "hello", "Russian to English")
expect(converter.convert("Ghbdtn")?.text == "Привет", "Preserve case")
expect(converter.convert("ghbdtn vbh")?.text == "привет мир", "Selection with spaces")
expect(converter.convert("ghbdtn\nVbh 😀")?.text == "привет\nМир 😀", "Newlines and emoji")
expect(converter.convert("123 😀") == nil, "No letters means no conversion")
expect(converter.convert("ghbdtn  ")?.text == "привет  ", "Trailing spaces")
expect(converter.convert("`~") == nil, "Punctuation alone is left alone")
expect(converter.convert("`Ghbdtn")?.text == "ёПривет", "Yo character")

func word(_ value: String, caret: Int? = nil) -> String? {
    guard let range = WordContext.lastWordRange(in: value, caretUTF16: caret ?? value.utf16.count) else { return nil }
    return (value as NSString).substring(with: range)
}
expect(word("one ghbdtn") == "ghbdtn", "Last word")
expect(word("one ghbdtn  ") == "ghbdtn  ", "Last word after spaces")
expect(word("one\nghbdtn\t") == "ghbdtn\t", "Line boundary")
expect(word("one\n") == nil, "Do not cross newline")
expect(word("    ") == nil, "Blank field")
expect(word("") == nil, "Empty field")
expect(word("one two three", caret: 7) == "two", "Word at caret")
expect(word("😀 ghbdtn") == "ghbdtn", "UTF16 position after emoji")
expect(word("abc", caret: -1) == nil, "Invalid caret")
expect(word("abc", caret: 99) == nil, "Caret out of range")

