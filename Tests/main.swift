let custom = ShortcutSpec(keyCode: 40, modifiers: [55, 58], tapCount: 1)
var keyMatcher = ShortcutMatcher(custom)
let match = keyMatcher.keyDown(40, flags: 0x28, isRepeat: false)
expect(match.trigger && match.suppress, "Custom Command Option K triggers and consumes key")
let repeatMatch = keyMatcher.keyDown(40, flags: 0x28, isRepeat: true)
expect(!repeatMatch.trigger && repeatMatch.suppress, "Key repeat suppressed without retriggering")
expect(keyMatcher.keyUp(40), "Matching key release suppressed")
expect(!keyMatcher.keyUp(40), "Unmatched key release forwarded")
let normalKey = keyMatcher.keyDown(0, flags: 0x28, isRepeat: false)
expect(!normalKey.trigger && !normalKey.suppress, "Other main key forwarded")
let wrongSide = keyMatcher.keyDown(40, flags: 0x30, isRepeat: false)
expect(!wrongSide.trigger && !wrongSide.suppress, "Custom shortcut distinguishes Command side")
let extraModifier = keyMatcher.keyDown(40, flags: 0x2A, isRepeat: false)
expect(!extraModifier.trigger && !extraModifier.suppress, "Extra Shift does not match")
var functionMatcher = ShortcutMatcher(ShortcutSpec(keyCode: 97, modifiers: [], tapCount: 1))
expect(functionMatcher.keyDown(97, flags: 0, isRepeat: false).trigger, "Single function key supported")
let encoded = try! JSONEncoder().encode(custom)
expect(try! JSONDecoder().decode(ShortcutSpec.self, from: encoded) == custom, "Shortcut survives saving and reload")
